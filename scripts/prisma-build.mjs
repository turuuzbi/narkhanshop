// Runs before `next build` and picks the database for this build:
//  - A postgres:// URL in the environment (e.g. Neon added from Vercel → Storage) → PostgreSQL:
//    writes a Postgres copy of prisma/schema.prisma, creates/updates the tables and seeds once.
//  - Otherwise → SQLite. Locally that's prisma/dev.db; on Vercel the app runs in demo mode
//    (a seeded SQLite file in /tmp, see src/lib/demo-db.ts).
import { execSync } from "node:child_process";
import fs from "node:fs";

const isPostgres = (v) => !!v && /^postgres(ql)?:\/\//.test(v);
const findUrl = (names, suffix) =>
  names.map((n) => process.env[n]).find(isPostgres) ??
  Object.entries(process.env).find(([k, v]) => suffix.test(k) && isPostgres(v))?.[1];

const pooled = findUrl(["DATABASE_URL", "POSTGRES_PRISMA_URL", "POSTGRES_URL"], /_(DATABASE_URL|POSTGRES_PRISMA_URL|POSTGRES_URL)$/);
const direct = findUrl(["DATABASE_URL_UNPOOLED", "POSTGRES_URL_NON_POOLING"], /_(DATABASE_URL_UNPOOLED|POSTGRES_URL_NON_POOLING)$/) ?? pooled;

const run = (cmd, env = {}) => execSync(cmd, { stdio: "inherit", env: { ...process.env, ...env } });

if (!pooled) {
  console.log(`▸ Database: SQLite${process.env.VERCEL ? " (Vercel demo mode — seeded in /tmp at startup)" : ""}`);
  run("npx prisma generate");
} else {
  console.log("▸ Database: PostgreSQL");
  const schema = fs
    .readFileSync("prisma/schema.prisma", "utf8")
    .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
  fs.mkdirSync("prisma/postgres", { recursive: true });
  fs.writeFileSync("prisma/postgres/schema.prisma", `// Generated by scripts/prisma-build.mjs from prisma/schema.prisma — do not edit.\n${schema}`);
  run("npx prisma generate --schema prisma/postgres/schema.prisma");
  // Schema changes go straight to the database (no migration history needed for the demo).
  run("npx prisma db push --schema prisma/postgres/schema.prisma --skip-generate", { DATABASE_URL: direct });
  run("npx tsx prisma/seed.ts --if-empty", { DATABASE_URL: direct });
}
